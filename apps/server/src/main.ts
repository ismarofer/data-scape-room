import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadAnswers, loadContent, loadEnv } from "./content.js";
import { loadModels, slotKeyOf } from "./models.js";
import { AiService } from "./ai/service.js";
import { loadCharacters, loadPrompts } from "./ai/characters.js";
import { llmFromEnv } from "./ai/llm.js";
import fs from "node:fs";
import YAML from "yaml";
import { openDb } from "./db.js";
import { Engine } from "./engine.js";
import { buildApp } from "./app.js";
import { Commission, loadCommission } from "./commission.js";
import { parseMlCsv } from "@codigo-alta/shared";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
loadEnv(root);
const content = loadContent(path.join(root, "content"));
const answers = { ...loadAnswers(process.env.ANSWERS_PATH ?? path.join(root, "data/dist/answers.public.json")), ...loadAnswers(path.join(root, "data/dist/build_answers.public.json")) };
const db = openDb(process.env.DB_PATH ?? path.join(root, "data/game.sqlite"));
const claims = JSON.parse(fs.readFileSync(path.join(root, "data/dist/r1c_claims.public.json"), "utf8"));
const rubrics = { "privacy_rubric.yaml": YAML.parse(fs.readFileSync(path.join(root, "content/privacy_rubric.yaml"), "utf8")) };
const mlFile = path.join(root, "data/dist/ml/ml_features.csv");
const mlRows = fs.existsSync(mlFile) ? parseMlCsv(fs.readFileSync(mlFile, "utf8")) : undefined;
// plain answer values stay on the server: they only fill the solution Lumi gives once a team asks for it
const valuesFile = path.join(root, "data/dist/answers.json");
const answerValues = fs.existsSync(valuesFile) ? Object.fromEntries(Object.entries(JSON.parse(fs.readFileSync(valuesFile, "utf8")) as Record<string, any>).map(([k, v]) => [k, v?.value])) : {};
const models = loadModels(path.join(root, "content"));
const engine = new Engine(db, { content, answers, rubrics, mlRows, answerValues, slotKey: slotKeyOf(models), claimIds: claims.map((c: any) => c.id), salt: process.env.ANSWER_SALT ?? "dev-salt-change-me", hintGate: process.env.DEV_NO_HINT_GATE !== "1" });
const llm = llmFromEnv(process.env);
const ai = new AiService(engine, { llm, characters: loadCharacters(path.join(root, "content")), prompts: loadPrompts(path.join(root, "content")), budgetEur: Number(process.env.AI_BUDGET_EUR_PER_SESSION ?? 5), priceEurPer1k: Number(process.env.AI_PRICE_EUR_PER_1K ?? 0.002) });
console.log(llm ? "IA live disponible (Azure Foundry)" : "IA live no configurada: solo scripted");
const pin = process.env.FACILITATOR_PIN ?? "0000";
if (pin === "0000") console.warn("[warn] FACILITATOR_PIN no definido: usando 0000 (solo desarrollo)");
const prompts = loadPrompts(path.join(root, "content"));
const commission = new Commission(engine, ai, loadCommission(path.join(root, "content")), prompts);
const app = buildApp({ engine, content, pin, commission, webDist: path.join(root, "apps/web/dist"), models, claims, ai, contentDir: path.join(root, "content") });
const port = Number(process.env.PORT ?? 3000);
await app.listen({ port, host: "0.0.0.0" });
console.log(`Código Alta escuchando en http://0.0.0.0:${port}`);
